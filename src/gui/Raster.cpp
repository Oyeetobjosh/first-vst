//-----------------------------------------------------------------------------------------------------------------------------------------
Raster::Raster (int width, int height)
: m_w (width)
, m_h (height)
, m_pixels ((size_t) width * height * 4, 0)
{
}

//-----------------------------------------------------------------------------------------------------------------------------------------
void Raster::putPixel (int x, int y, uint8_t r, uint8_t g, uint8_t b, uint8_t a)
{
    if (x < 0 || y < 0 || x >= m_w || y >= m_h || a == 0)
        return;

    const int i = pixelIndex (x, y);

    // Straight-alpha "over" blending
    const float sa = a / 255.0f;
    const float da = m_pixels[i + 3] / 255.0f;

    if (sa >= 1.0f)
    {
        m_pixels[i] = r;
        m_pixels[i + 1] = g;
        m_pixels[i + 2] = b;
        m_pixels[i + 3] = 255;
        return;
    }

    const float outA = sa + da * (1.0f - sa);
    const float blend = (outA > 0.0f) ? (sa / outA) : 0.0f;

    m_pixels[i] = (uint8_t) (r * blend + m_pixels[i] * (1.0f - blend));
    m_pixels[i + 1] = (uint8_t) (g * blend + m_pixels[i + 1] * (1.0f - blend));
    m_pixels[i + 2] = (uint8_t) (b * blend + m_pixels[i + 2] * (1.0f - blend));
    m_pixels[i + 3] = (uint8_t) (outA * 255.0f);
}

//-----------------------------------------------------------------------------------------------------------------------------------------
Raster::PixelRGBA Raster::pixel (int x, int y) const
{
    PixelRGBA p{ 0, 0, 0, 0 };
    if (x < 0 || y < 0 || x >= m_w || y >= m_h)
        return p;

    const int i = (y * m_w + x) * 4;
    p.r = m_pixels[i];
    p.g = m_pixels[i + 1];
    p.b = m_pixels[i + 2];
    p.a = m_pixels[i + 3];
    return p;
}

//-----------------------------------------------------------------------------------------------------------------------------------------
void Raster::clear (uint8_t r, uint8_t g, uint8_t b)
{
    for (size_t i = 0; i < m_pixels.size (); i += 4)
    {
        m_pixels[i] = r;
        m_pixels[i + 1] = g;
        m_pixels[i + 2] = b;
        m_pixels[i + 3] = 255;
    }
}

//-----------------------------------------------------------------------------------------------------------------------------------------
void Raster::fillRect (int x, int y, int w, int h, uint8_t r, uint8_t g, uint8_t b, uint8_t a)
{
    x = std::max (0, std::min (m_w, x));
    y = std::max (0, std::min (m_h, y));
    w = std::max (0, std::min (m_w - x, w));
    h = std::max (0, std::min (m_h - y, h));

    for (int j = y; j < y + h; ++j)
        for (int i = x; i < x + w; ++i)
            putPixel (i, j, r, g, b, a);
}

//-----------------------------------------------------------------------------------------------------------------------------------------
void Raster::strokeRect (int x, int y, int w, int h, uint8_t r, uint8_t g, uint8_t b, uint8_t a)
{
    drawLine (x, y, x + w - 1, y, r, g, b, a);
    drawLine (x, y + h - 1, x + w - 1, y + h - 1, r, g, b, a);
    drawLine (x, y, x, y + h - 1, r, g, b, a);
    drawLine (x + w - 1, y, x + w - 1, y + h - 1, r, g, b, a);
}

//-----------------------------------------------------------------------------------------------------------------------------------------
void Raster::fillRoundRect (int x, int y, int w, int h, int r, uint8_t r0, uint8_t g0, uint8_t b0, uint8_t a)
{
    r = std::max (0, std::min (r, std::min (w, h) / 2));
    fillRect (x + r, y, w - 2 * r, h, r0, g0, b0, a);
    fillRect (x, y + r, w, h - 2 * r, r0, g0, b0, a);
    fillCircle (x + r, y + r, r, r0, g0, b0, a);
    fillCircle (x + w - r - 1, y + r, r, r0, g0, b0, a);
    fillCircle (x + r, y + h - r - 1, r, r0, g0, b0, a);
    fillCircle (x + w - r - 1, y + h - r - 1, r, r0, g0, b0, a);
}

//-----------------------------------------------------------------------------------------------------------------------------------------
void Raster::strokeRoundRect (int x, int y, int w, int h, int r, uint8_t r0, uint8_t g0, uint8_t b0, uint8_t a)
{
    r = std::max (1, std::min (r, std::min (w, h) / 2));
    drawLine (x + r, y, x + w - r - 1, y, r0, g0, b0, a);
    drawLine (x + r, y + h - 1, x + w - r - 1, y + h - 1, r0, g0, b0, a);
    drawLine (x, y + r, x, y + h - r - 1, r0, g0, b0, a);
    drawLine (x + w - 1, y + r, x + w - 1, y + h - r - 1, r0, g0, b0, a);
    strokeArc (x + r, y + r, r, M_PI, 3.0 * M_PI / 2.0, r0, g0, b0, a);
    strokeArc (x + w - r - 1, y + r, r, 3.0 * M_PI / 2.0, 2.0 * M_PI, r0, g0, b0, a);
    strokeArc (x + r, y + h - r - 1, r, M_PI / 2.0, M_PI, r0, g0, b0, a);
    strokeArc (x + w - r - 1, y + h - r - 1, r, 0.0, M_PI / 2.0, r0, g0, b0, a);
}

//-----------------------------------------------------------------------------------------------------------------------------------------
void Raster::drawLine (int x0, int y0, int x1, int y1, uint8_t r, uint8_t g, uint8_t b, uint8_t a)
{
    int dx = std::abs (x1 - x0);
    int dy = std::abs (y1 - y0);
    int sx = (x0 < x1) ? 1 : -1;
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx - dy;

    for (;;)
    {
        putPixel (x0, y0, r, g, b, a);
        if (x0 == x1 && y0 == y1)
            break;
        const int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 < dx)  { err += dx; y0 += sy; }
    }
}

//-----------------------------------------------------------------------------------------------------------------------------------------
void Raster::fillCircle (int cx, int cy, int r, uint8_t r0, uint8_t g0, uint8_t b0, uint8_t a0,
                         uint8_t r1, uint8_t g1, uint8_t b1, uint8_t a1)
{
    if (r < 0)
        return;

    const double rad = std::max (1.0, (double) r);

    for (int y = -r; y <= r; ++y)
    {
        for (int x = -r; x <= r; ++x)
        {
            if (x * x + y * y > r * r)
                continue;

            const double d = std::sqrt ((double) (x * x + y * y)) / rad;   // 0 = center, 1 = edge
            const uint8_t rr = (uint8_t) (r0 + (r1 - r0) * d);
            const uint8_t gg = (uint8_t) (g0 + (g1 - g0) * d);
            const uint8_t bb = (uint8_t) (b0 + (b1 - b0) * d);
            const uint8_t aa = (uint8_t) (a0 + (double) (a1 - a0) * d);
            putPixel (cx + x, cy + y, rr, gg, bb, aa);
        }
    }
}

//-----------------------------------------------------------------------------------------------------------------------------------------
void Raster::strokeCircle (int cx, int cy, int r, uint8_t r0, uint8_t g0, uint8_t b0, uint8_t a0)
{
    if (r < 0)
        return;

    int x = r;
    int y = 0;
    int err = 1 - r;

    while (x >= y)
    {
        putPixel (cx + x, cy + y, r0, g0, b0, a0);
        putPixel (cx - x, cy + y, r0, g0, b0, a0);
        putPixel (cx + x, cy - y, r0, g0, b0, a0);
        putPixel (cx - x, cy - y, r0, g0, b0, a0);
        putPixel (cx + y, cy + x, r0, g0, b0, a0);
        putPixel (cx - y, cy + x, r0, g0, b0, a0);
        putPixel (cx + y, cy - x, r0, g0, b0, a0);
        putPixel (cx - y, cy - x, r0, g0, b0, a0);
        ++y;
        if (err < 0)
            err += 2 * y + 1;
        else
        {
            --x;
            err += 2 * (y - x) + 1;
        }
    }
}

//-----------------------------------------------------------------------------------------------------------------------------------------
void Raster::strokeArc (int cx, int cy, int r, double a0, double a1, uint8_t r0, uint8_t g0, uint8_t b0, uint8_t aa)
{
    if (r < 1)
        return;

    const double step = 0.02;                                    // radians per sample
    const double span = a1 - a0;
    const int samples = (int) (std::fabs (span) / step) + 1;

    for (int i = 0; i <= samples; ++i)
    {
        const double a = a0 + span * i / samples;
        putPixel (cx + (int) std::lround (std::cos (a) * r),
                  cy + (int) std::lround (std::sin (a) * r), r0, g0, b0, aa);
    }
}

//-----------------------------------------------------------------------------------------------------------------------------------------
bool Raster::glyphAt (char c, int scale, int gx, int gy)
{
    if (c < 0 || c > 127)
        return false;

    const char* glyph = kFont[c];
    if (!glyph)
        return false;

    const int row = gy / scale;
    const int col = gx / scale;
    if (row < 0 || row > 6 || col < 0 || col > 4)
        return false;

    return glyph[row * 6 + col] == '#';
}

//-----------------------------------------------------------------------------------------------------------------------------------------
void Raster::drawText (const char* text, int x, int y, uint8_t r, uint8_t g, uint8_t b, uint8_t a, int scale)
{
    if (!text || scale < 1)
        return;

    int cx = x;
    for (const char* p = text; *p; ++p)
    {
        const int gw = 6 * scale;
        for (int gy = 0; gy < 7 * scale; ++gy)
            for (int gx = 0; gx < gw; ++gx)
                if (glyphAt (*p, scale, gx, gy))
                    putPixel (cx + gx, y + gy, r, g, b, a);
        cx += gw;
    }
}

//-----------------------------------------------------------------------------------------------------------------------------------------
int Raster::textWidth (const char* text, int scale) const
{
    if (!text)
        return 0;
    return std::strlen (text) * 6 * scale;
}

//-----------------------------------------------------------------------------------------------------------------------------------------
int Raster::textHeight (int scale)
{
    return 7 * scale;
}
